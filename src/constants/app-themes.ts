export function isAppThemeId(value: unknown): value is AppThemeId {
  return APP_THEME_IDS.includes(value as AppThemeId);
}

/** The variant for a theme in light or dark mode; unknown ids get Flare's. */
export function appTheme(id: AppThemeId, mode: 'light' | 'dark'): ThemeVariant {
  const theme = APP_THEMES.find((candidate) => candidate.id === id) ?? APP_THEMES[0];
  return theme[mode];
}
