/**
 * Flare's app themes: ten themes, each with a light and a dark variant. A theme sets three
 * things together: the app's colours, the terminal's colours (an xterm.js TerminalTheme)
 * and its shape (type, corners, borders, shadows, glow). docs/design.md explains when to use
 * each token; the values come from the design system's tokens/themes.json.
 *
 * - colors: the tokens useTheme() returns. primaryText is the accent wherever it is text or
 *   an icon on a surface; primary stays for fills, borders, the cursor and focus. They are
 *   equal except where the accent is too light to read as text (Graphite's lime, Concrete's
 *   yellow).
 * - terminal: the terminal is the screen, so its background is the app's.
 * - shape: per theme. Fonts are faces from theme.ts's FontRoles, never fontWeight.
 *
 * The terminal palettes of the well-known themes are under permissive licences (credited in
 * README.md):
 *
 * - Tokyo Night: folke/tokyonight.nvim's terminal extras, Night and Day (Apache-2.0)
 * - Catppuccin: catppuccin/kitty, Mocha and Latte (MIT)
 * - Solarized: Ethan Schoonover's palette (MIT), with bright black lifted to base01 so dim
 *   text stays visible on the dark background
 * - Gruvbox: morhetz/gruvbox (MIT/X11), medium contrast
 */

import type { FontFace, TerminalTheme } from './theme';

