export type AppThemeId = (typeof APP_THEME_IDS)[number];

export const DEFAULT_APP_THEME: AppThemeId = 'flare';

export type AppColors = {
  background: string;
  backgroundElement: string;
  backgroundSelected: string;
  backgroundRaised: string;
  border: string;
  text: string;
  textSecondary: string;
  primary: string;
  onPrimary: string;
  primaryMuted: string;
  primaryText: string;
  success: string;
  warning: string;
  danger: string;
  attention: string;
  shadow: string;
  keyboard: string;
  key: string;
  keyFunction: string;
  keyShadow: string;
  keyArmed: string;
  primaryBorder: string;
  segmentTrack: string;
  segmentThumb: string;
};

export type ThemeShape = {
  /** ui: everything people read. display: title, subtitle. label: overline. mono: machine text. */
  fonts: { ui: FontFace; display: FontFace; label: FontFace; mono: FontFace };
  displayWeight: 400 | 500 | 600 | 700;
  /** letterSpacing for title/subtitle. */
  displayTracking: number;
  displayCase: 'none' | 'uppercase';
  labelCase: 'none' | 'uppercase';
  labelTracking: number;
  labelWeight: 400 | 500 | 600 | 700;
  /** Corners. key: the keyboard's keys; dot: status lights (0 = square). */
  radius: { small: number; medium: number; large: number; pill: number; key: number; dot: number };
  /** Cards, fields, rows and tabs; 1 means a hairline. */
  borderWidth: number;
  /** Selected picker tile. */
  borderWidthStrong: number;
  /** boxShadow strings ('none' = omit). */
  shadowCard: string;
  shadowFloat: string;
  shadowControl: string;
  /** Extra boxShadow on primary fills, the cursor and the live underline. */
  glowPrimary: string;
  /** Wordmark + display text glow (textShadowColor/Radius), or null. */
  textGlow: { color: string; radius: number } | null;
  /** Pressed: scale, and translate (Concrete presses into its hard shadow). */
  pressScale: number;
  pressShift: number;
  /** The Material Symbols cut the design names (not drawn yet: expo-symbols has one cut). */
  iconStyle: 'outlined' | 'rounded' | 'sharp';
};

export type ThemeVariant = { colors: AppColors; terminal: TerminalTheme; shape: ThemeShape };
export type AppTheme = {
  id: AppThemeId;
  name: string;
  family: string;
  description: string;
  light: ThemeVariant;
  dark: ThemeVariant;
};

